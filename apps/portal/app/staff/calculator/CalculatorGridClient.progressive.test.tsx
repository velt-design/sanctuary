import {act} from 'react';
import {afterEach,expect,it,vi} from 'vitest';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {renderIntoDocument} from '../../../../../test/reactHarness';
import CalculatorGridClient from './CalculatorGridClient';
import {makeDefaultCalculatorInputs} from './calculatorInputs';
import type {EstimateDetail} from '@/lib/estimates/types';
const mocks=vi.hoisted(()=>({router:{replace:vi.fn(),push:vi.fn()},params:new URLSearchParams('editEstimateId=fictional-saved'),toast:{success:vi.fn(),error:vi.fn()}}));
vi.mock('next/navigation',()=>({useRouter:()=>mocks.router,useSearchParams:()=>mocks.params}));
vi.mock('@/components/auth/PortalAuthProvider',()=>({usePortalSession:()=>({email:'fictional@example.invalid',role:'staff'})}));
vi.mock('@/components/ui/toast/ToastProvider',()=>({useToast:()=>mocks.toast}));
const flush=()=>act(async()=>{await new Promise(resolve=>setTimeout(resolve,30));});
afterEach(()=>{document.body.innerHTML='';vi.restoreAllMocks();});
it('mounts the actual Calculator before the saved identity resolves without starting costing or persisting defaults, then retains its controls',async()=>{
  let resolve!:(estimate:EstimateDetail)=>void;
  const saved=new Promise<EstimateDetail>(yes=>{resolve=yes;});
  const persist=vi.fn(async()=>({sessionStored:true,workingCopyStored:false}));
  const request=vi.fn(async()=>{throw new Error('Fictional costing unavailable');});
  const client=new QueryClient({defaultOptions:{queries:{retry:false}}});
  const estimateLoader=vi.fn(()=>saved);
  const view=renderIntoDocument(<QueryClientProvider client={client}><CalculatorGridClient sessionReads={{draftPersistence:{restore:async()=>null,persist},estimateLoader}} costingRequest={request} readOnly/></QueryClientProvider>);
  await flush();
  const length=view.container.querySelector<HTMLInputElement>('#lengthM')!;
  const bar=view.container.querySelector('[data-calculator-command-bar]');
  const materials=[...view.container.querySelectorAll<HTMLButtonElement>('[role="tab"]')].find(button=>button.textContent==='Materials')!;
  expect(length).not.toBeNull();expect(length.disabled).toBe(true);expect(length.value).toBe('');
  expect(view.container.textContent).toContain('Reading saved draft');expect(view.container.querySelector('[data-calculator-command-save]')).not.toBeNull();
  act(()=>materials.click());expect(materials.getAttribute('aria-selected')).toBe('true');
  await act(async()=>{await new Promise(yes=>setTimeout(yes,250));});
  expect(request).not.toHaveBeenCalled();expect(persist).not.toHaveBeenCalled();expect(estimateLoader).toHaveBeenCalledTimes(1);
  const inputs=makeDefaultCalculatorInputs();inputs.modules[0].lengthM='8.4';
  await act(async()=>resolve({id:'fictional-saved',projectId:'fictional-project',createdAt:'2026-10-22T00:00:00Z',status:'draft',summary:{},versionLabel:'V1',isActiveDraft:true,hasSentQuote:false,jobPackEligible:false,jobPackGeneratedAt:null,jobPackQuoteVersionId:null,calculatorSnapshot:{inputs},editability:{isLocked:false,lockReason:null,lockedAt:null,lockedByQuoteVersionId:null,lockedByQuoteRef:null,lockedByQuoteVersionNumber:null,hasDraftQuotes:false,draftQuoteCount:0}}));
  await flush();
  expect(view.container.querySelector('#lengthM')).toBe(length);expect(length.value).toBe('8.4');expect(length.disabled).toBe(false);
  expect(view.container.querySelector('[data-calculator-command-bar]')).toBe(bar);expect(materials.getAttribute('aria-selected')).toBe('true');
  expect(view.container.querySelector<HTMLButtonElement>('[data-calculator-command-save]')?.disabled).toBe(true);
  view.unmount();client.clear();
});
