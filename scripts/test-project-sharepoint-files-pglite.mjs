  assert.equal((await provision('claim')).claimed, false);
  await assert.rejects(provision('complete', fresh, { itemId: 'newroot', evidenceSha256: binding }, existing), /Lease expired/);
  await assert.rejects(admin('import', { binding, projectId: fresh, itemId: 'other', label: 'Other', evidenceSha256: binding }), /Provision in progress/);
  await provision('fail', fresh, { code: 'source_unavailable' });
  assert.equal((await provision('claim')).claimed, false);
  await db.exec("update private.project_folder_provisions set next_attempt=now()-interval '1 minute'");
  assert.equal((await provision('claim')).claimed, true);
  await provision('complete', fresh, { itemId: 'newroot', evidenceSha256: binding });
  assert.equal((await provision('claim')).claimed, false);
  const row = { binding, projectId: existing, itemId: 'historical1', label: 'Verified root', evidenceSha256: binding };
  assert.equal((await admin('import', row)).replayed, false);
